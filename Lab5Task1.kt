fun main() {
    val letter: Char = 'K'
    val word: String = "K"

    println(letter)
    println(word)

    // Проверяем первый символ строки
    println(word[0])
}

// Разница: 'K' — это отдельный символ (Char в одинарных кавычках),
// а "K" — это строка (String в двойных кавычках, даже если там всего одна буква).